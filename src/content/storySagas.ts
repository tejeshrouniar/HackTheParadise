// EXPORTED SAGAS REGISTRY
// ─────────────────────────────────────────────────────────────────────────────
export const ALL_SAGAS: MagicalSaga[] = [
  SAGA_ELDORIA,
  SAGA_CHRONOS,
  SAGA_SYLVA,
  SAGA_FORGE,
  SAGA_ATLANTIS,
];

export function getSagaById(id: string): MagicalSaga | undefined {
  return ALL_SAGAS.find((s) => s.id === id);
}

export function getAllChapters(): StoryChapterData[] {
  return ALL_SAGAS.flatMap((s) => s.chapters);
}

export function getChapterBySagaAndIndex(sagaId: string, index: number): StoryChapterData | undefined {
  const saga = getSagaById(sagaId);
  return saga?.chapters[index];
}
